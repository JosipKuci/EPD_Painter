#!/usr/bin/env python3
"""Turn a GIF into the C header the gif_player sketch plays.

    python3 gif2h.py my.gif            # writes gif_data.h next to this script
    python3 gif2h.py --demo            # regenerates the bundled demo animation

The GIF is embedded as-is: decoding happens on the board. Keep it small
(a few hundred KB) - it lives in flash, and huge_app gives ~3 MB in total.
Small GIFs are fine: the sketch scales them up to fill the panel.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "gif_data.h")


def demo_gif(path):
    """A 160x110 bouncing ball and spinning bar, 24 frames, 4 greys."""
    import math
    from PIL import Image, ImageDraw

    W, H, N = 160, 110, 24
    frames = []
    for i in range(N):
        im = Image.new("L", (W, H), 255)
        d = ImageDraw.Draw(im)
        d.rectangle([0, 0, W - 1, H - 1], outline=0, width=2)
        t = i / N
        bx = 20 + (W - 40) * (0.5 - 0.5 * math.cos(2 * math.pi * t))
        by = H - 22 - 60 * abs(math.sin(2 * math.pi * t))
        d.ellipse([bx - 14, by - 14, bx + 14, by + 14], fill=0)
        d.ellipse([bx - 18, H - 10, bx + 18, H - 4], fill=170)
        a = 2 * math.pi * t
        cx, cy, r = W - 30, 26, 18
        d.line([cx - r * math.cos(a), cy - r * math.sin(a),
                cx + r * math.cos(a), cy + r * math.sin(a)], fill=85, width=5)
        frames.append(im.convert("P"))
    frames[0].save(path, save_all=True, append_images=frames[1:],
                   duration=50, loop=0, optimize=False, disposal=1)


def write_header(gif_path):
    data = open(gif_path, "rb").read()
    if data[:3] != b"GIF":
        sys.exit(f"{gif_path} is not a GIF")
    w = data[6] | data[7] << 8
    h = data[8] | data[9] << 8
    if w > 480:
        sys.exit(f"{w} px wide: AnimatedGIF on ESP32 stops at 480. Shrink it first.")
    print(f"{w} x {h}")
    name = os.path.basename(gif_path)
    with open(OUT, "w") as f:
        f.write(f"// Generated by gif2h.py from {name} ({len(data)} bytes).\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("static const uint8_t gif_data[] = {\n")
        for i in range(0, len(data), 16):
            f.write("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",\n")
        f.write("};\n")
    print(f"wrote {OUT}: {len(data)} bytes")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    if sys.argv[1] == "--demo":
        import tempfile
        tmp = os.path.join(tempfile.mkdtemp(), "demo.gif")
        demo_gif(tmp)
        write_header(tmp)
    else:
        write_header(sys.argv[1])
